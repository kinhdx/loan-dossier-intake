"""Writes evaluation results to reports/ as JSON (complete) and Markdown (summary and failures)."""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

REPORTS = Path(__file__).resolve().parents[3] / "reports"

CAVEAT = ("Synthetic data: every document was generated by fixtures/generate.py. Results show how the pipeline "
          "behaves on clean, consistent layouts and should be read as an upper bound for real documents.")


def _table(summary: dict) -> str:
    return "\n".join(["| Metric | Value |", "|---|---|"] + [f"| {k} | {v} |" for k, v in summary.items()])


def _subset_table(summaries: dict[str, dict]) -> str:
    names = list(summaries)
    metrics = list(next(iter(summaries.values())))
    lines = ["| Metric | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    lines += [f"| {m} | " + " | ".join(str(summaries[n].get(m)) for n in names) + " |" for m in metrics]
    return "\n".join(lines)


def write(kind: str, result: dict) -> Path:
    REPORTS.mkdir(exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M")
    base = REPORTS / f"{kind}-{stamp}-{result['model']}"
    base.with_suffix(".json").write_text(json.dumps(result, ensure_ascii=False, indent=1), encoding="utf-8")
    lines = [f"# {kind.upper()} evaluation: {result['model']}", "", f"Run: {stamp}"]
    if kind == "idp":
        lines += [f"Classifier: {result['classify_model']}", "", CAVEAT, "", _subset_table(result["summary"]), "",
                  "## Dossiers with a wrong decision or an unexpected finding", "",
                  "| Dossier | Planted defect | Expected | Got | Findings |", "|---|---|---|---|---|"]
        for r in result["rows"]:
            if not r["decision_ok"] or r["unexpected_findings"] or (r["expected_findings"] and not r["defect_found"]):
                lines.append(f"| {r['dossier']} | {r['defect']} | {r['expected_decision']} | {r['decision']} "
                             f"| {', '.join(r['findings']) or '-'} |")
        lines += ["", "## Field misses", "", "| Dossier | Document | Field | Expected | Got |", "|---|---|---|---|---|"]
        for r in result["rows"]:
            for m in r["field_misses"]:
                lines.append(f"| {r['dossier']} | {m['document']} | {m['field']} | {m['expected']} | {m['got']} |")
    elif kind == "retrieval":
        lines += [f"Embedding model: {result['embedding_model']}, top-k: {result['top_k']}, "
                  f"questions: {result['questions']}", "",
                  "Lexical weight 0 is embedding search alone. The weight was chosen on this same question set, "
                  "so the gain is an optimistic estimate until it is confirmed on held-out questions.", "",
                  "| Lexical weight | Hit@1 % | Hit@k % | MRR |", "|---|---|---|---|"]
        lines += [f"| {r['lexical_weight']} | {r['hit_at_1_pct']} | {r['hit_at_k_pct']} | {r['mrr']} |"
                  for r in result["rows"]]
    else:
        lines += [f"Embedding model: {result['embedding_model']}, top-k: {result['top_k']}", "", CAVEAT, "",
                  _table(result["summary"]), "", "## Questions not fully correct", "",
                  "| ID | In scope | Gold rank | Facts | Cites gold | Answerable | Answer |", "|---|---|---|---|---|---|---|"]
        for r in result["rows"]:
            ok = (r["facts_ok"] and r["cites_gold"]) if r["in_scope"] else not r["answerable"]
            if not ok:
                answer = r["answer"].replace("|", "/").replace("\n", " ")[:160]
                lines.append(f"| {r['id']} | {r['in_scope']} | {r['rank']} | {r['facts_ok']} | {r['cites_gold']} "
                             f"| {r['answerable']} | {answer} |")
    path = base.with_suffix(".md")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
